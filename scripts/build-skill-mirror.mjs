// Regenerates packages/core/src/skill-mirror.ts, the default skill setup Dryland compares a repo with.
// Usage: node scripts/build-skill-mirror.mjs [skills-dir]   (default: .agents/skills of this repo)
import { readdir, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { format, resolveConfig } from "prettier";

// core's sources are TypeScript with parameter properties, which Node cannot strip, so bundle the one module needed.
const bundled = await build({
  entryPoints: [fileURLToPath(new URL("../packages/core/src/skill-setup.ts", import.meta.url))],
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
});
const code = bundled.outputFiles[0].text;
const { fingerprintSkill } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);

/** Skills Dryland routes to or cannot work without; a repo missing one is a modified setup. */
const CORE = [
  "code-review",
  "implement",
  "implement-spec",
  "pr",
  "setup-matt-pocock-skills",
  "to-spec",
  "to-tickets",
  "triage",
  "wayfinder",
];

const root = resolve(process.argv[2] ?? ".agents/skills");
const names = (await readdir(root, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() || entry.isSymbolicLink())
  .map((entry) => entry.name)
  .sort();
const skills = {};
for (const name of names) skills[name] = await fingerprintSkill(join(root, name));

const lines = Object.entries(skills).map(([name, print]) => `    ${JSON.stringify(name)}: ${JSON.stringify(print)},`);
const source = `// Generated by scripts/build-skill-mirror.mjs from mattpocock/skills; do not edit by hand.
import type { SkillMirror } from "./skill-setup.ts";

export const DEFAULT_SKILL_MIRROR: SkillMirror = {
  skills: {
${lines.join("\n")}
  },
  core: ${JSON.stringify(CORE)},
};
`;
const target = fileURLToPath(new URL("../packages/core/src/skill-mirror.ts", import.meta.url));
// Formatted here so that the file passes `prettier --check` as generated.
await writeFile(target, await format(source, { ...(await resolveConfig(target)), filepath: target }));
console.log(`Mirrored ${names.length} skills.`);
